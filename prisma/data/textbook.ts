/** Printed pages of a paragraph: up to the next paragraph or the chapter review page. */
export function topicPages(t: TextbookTopic): [number, number] {
  const i = TEXTBOOK_TOPICS.indexOf(t);
  const next = TEXTBOOK_TOPICS[i + 1];
  if (t.lastPage) return [t.page, t.lastPage];
  const chapter = TEXTBOOK_CHAPTERS.find((c) => c.n === t.chapter)!;
  if (!next || next.chapter !== t.chapter) {
    const end = chapter.review ? chapter.review.page - 1 : next ? next.page - 3 : t.page + 2;
    return [t.page, Math.max(t.page, end)];
  }
  return [t.page, Math.max(t.page, next.page - 1)];
}

export const pagesLabel = ([a, b]: [number, number]) => (a === b ? `${a}-бет` : `${a}–${b} беттер`);

// ───────────────────────────── plan ─────────────────────────────

type PlanItem = { kind: "demo"; number: number; title: string } | { kind: "topic"; topic: TextbookTopic };

/** Lessons per chapter in teaching order: demo lessons keep their order, new paragraphs slot in by § number. */
export function lessonPlan(): { chapter: (typeof TEXTBOOK_CHAPTERS)[number]; items: PlanItem[] }[] {
  const covered = new Set(Object.values(DEMO_LESSON_TOPICS).flat());
  const demoSection = (n: number) => DEMO_LESSONS.find((d) => d.number === n)!.section + 1; // section 0 → chapter 1
  return TEXTBOOK_CHAPTERS.map((chapter) => {
    const keyed: { key: number; item: PlanItem }[] = [];
    let last = 0;
    for (const d of DEMO_LESSONS.filter((x) => demoSection(x.number) === chapter.n)) {
      const topics = DEMO_LESSON_TOPICS[d.number] ?? [];
      last = DEMO_LESSON_ORDER[d.number] ?? (topics.length ? Math.max(...topics) : last + 0.5);
      keyed.push({ key: last, item: { kind: "demo", number: d.number, title: d.title } });
    }
    for (const t of TEXTBOOK_TOPICS.filter((x) => x.chapter === chapter.n && !covered.has(x.n))) {
      keyed.push({ key: t.n, item: { kind: "topic", topic: t } });
    }
    keyed.sort((a, b) => a.key - b.key);
    return { chapter, items: keyed.map((k) => k.item) };
  });
}
