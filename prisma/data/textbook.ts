// ───────────────────────────── helpers ─────────────────────────────

function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

const cite = (page: number | string) => `Оқулық, ${page}-бет.`;

/** Single choice. The correct answer is written first and placed at a stable pseudo-random position. */
function sc(page: number | string, prompt: string, correct: string, ...wrong: string[]): DemoQuestion {
  const options = [...wrong];
  const at = hash(prompt) % (wrong.length + 1);
  options.splice(at, 0, correct);
  return { type: "SINGLE_CHOICE", prompt, options, correct: at, explanation: cite(page) };
}

function tf(page: number | string, prompt: string, isTrue: boolean, note?: string): DemoQuestion {
  return { type: "TRUE_FALSE", prompt, isTrue, explanation: note ? `${note} ${cite(page)}` : cite(page) };
}

function match(page: number | string, prompt: string, pairs: [string, string][]): DemoQuestion {
  return { type: "MATCHING", prompt, pairs, explanation: cite(page) };
}

